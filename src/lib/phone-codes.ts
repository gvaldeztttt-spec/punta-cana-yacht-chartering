export function getCountryPhoneCode(iso: string): CountryPhoneCode | undefined {
  return COUNTRY_PHONE_CODES.find((country) => country.iso === iso);
}

export function getSortedCountryPhoneCodes(): CountryPhoneCode[] {
  return [...COUNTRY_PHONE_CODES].sort((a, b) => a.name.en.localeCompare(b.name.en));
}

export function getCountryPhoneLabel(
  country: CountryPhoneCode,
  locale: "en" | "es",
): string {
  return `${country.name[locale]} (${country.dial})`;
}

export function normalizePhoneDigits(value: string): string {
  return value.replace(/\D/g, "");
}

export function formatFullPhone(iso: string, localNumber: string): string {
  const country = getCountryPhoneCode(iso);
  if (!country) return normalizePhoneDigits(localNumber);
  const digits = normalizePhoneDigits(localNumber);
  const dialDigits = country.dial.replace("+", "");
  if (digits.startsWith(dialDigits)) return `+${digits}`;
  return `${country.dial}${digits}`;
}

export function formatDisplayPhone(iso: string, localNumber: string): string {
  const full = formatFullPhone(iso, localNumber);
  if (full.startsWith("+1") && full.length === 12) {
    return `+1 (${full.slice(2, 5)}) ${full.slice(5, 8)}-${full.slice(8)}`;
  }
  if (full.startsWith("+1") && full.length === 13) {
    return `+1 (${full.slice(2, 5)}) ${full.slice(5, 8)}-${full.slice(8)}`;
  }
  return full;
}

export function validatePhoneNumber(iso: string, localNumber: string): boolean {
  if (!getCountryPhoneCode(iso)) return false;
  const digits = normalizePhoneDigits(localNumber);
  return digits.length >= 6 && digits.length <= 15;
}
